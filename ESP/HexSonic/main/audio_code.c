uint8 i2cWriteOneByte(uint8 SlaveAddress, uint8 reg, uint8 data) {
    esp_err_t err = audio_write_reg(reg, data);
    if (err != ESP_OK) {
        return 0;
    }
    return 1;
}

uint8 ACM86xx_Write_REG(uint8 SlaveAddress, uint16 data_length, const struct REG_TAB *reg_address) {
    int i;
    const struct REG_TAB *reg_access_ptr = reg_address;
    ESP_LOGI(TAG, "ACM86xx_Write_REG_data_length=%d", data_length);
    for (i = 0; i < data_length; i++) {
        if (i2cWriteOneByte(SlaveAddress, reg_access_ptr->Address, reg_access_ptr->Data) == FALSE)
            return FALSE;
        reg_access_ptr++;
    }
    return 1;
}

void ACM86xx_Mute(void) {
    i2cWriteOneByte(ACM86xx_IIC_ADDR, 0x00, 0x00);
    i2cWriteOneByte(ACM86xx_IIC_ADDR, 0x04, 0x0e);
}

void ACM86xx_UnMute(void) {
    i2cWriteOneByte(ACM86xx_IIC_ADDR, 0x00, 0x00);
    i2cWriteOneByte(ACM86xx_IIC_ADDR, 0x04, 0x03);
}

uint8 PostEQEnable = 1;
void ACM86xx_POSTEQ_ONOFF(void) {
    if (PostEQEnable == 1) {
        i2cWriteOneByte(ACM86xx_IIC_ADDR, 0x00, 0x00);
        i2cWriteOneByte(ACM86xx_IIC_ADDR, 0x05, 0x20);
    } else {
        i2cWriteOneByte(ACM86xx_IIC_ADDR, 0x00, 0x00);
        i2cWriteOneByte(ACM86xx_IIC_ADDR, 0x05, 0x28);
    }
}

//***********************ACM86xx is able to provide -110dB to 48dB volume, current driver only inlcudes normal 16 sets volume table***********************/
void volumeControl(uint8 vol) {
    if (vol > 99)
        vol = 99;
    audio_i2c_volume = vol;
    unsigned char v1, v2, v3, v4;
    unsigned int tmp = 0;

    int index = vol / 2;
    if (index > 0) {
        int index1 = index - 1;
        tmp = ((my_acm8615VolTable[49 - index]) + (my_acm8615VolTable[49 - index1])) / 2;
    } else {
        tmp = (my_acm8615VolTable[49 - index]);
    }

    v1 = (tmp >> 24) & 0xff;
    v2 = (tmp >> 16) & 0xff;
    v3 = (tmp >> 8) & 0xff;
    v4 = (tmp) & 0xff;

    i2cWriteOneByte(ACM86xx_IIC_ADDR, 0x00, 0x04);
    i2cWriteOneByte(ACM86xx_IIC_ADDR, 0x40, v1);
    i2cWriteOneByte(ACM86xx_IIC_ADDR, 0x41, v2);
    i2cWriteOneByte(ACM86xx_IIC_ADDR, 0x42, v3);
    i2cWriteOneByte(ACM86xx_IIC_ADDR, 0x43, v4);
    vTaskDelay(10 / portTICK_PERIOD_MS);
}

//***********************os_delay_ms... refer to your own os driver implement***********************/
char ACM86xx_init(uint8 vol) {
    // TBD.... power up PVDD, DVDD, then pull up PDNz, delay 5ms
    if (ACM86xx_Write_REG(ACM86xx_IIC_ADDR, (sizeof(m_reg_tab_initialization) / 2), &m_reg_tab_initialization[0]) == 0) {
        return -1;
    }
    vTaskDelay(10 / portTICK_PERIOD_MS);
    // ACM86xx_REGISTER_COUNT
    if (ACM86xx_Write_REG(ACM86xx_IIC_ADDR, (sizeof(m_reg_tab) / 2), &m_reg_tab[0]) == 0) {
        return -1;
    }
    volumeControl(vol);
    ESP_LOGI(TAG, "audio init end");
    return 0;
}

// 找到这行并修改
char init_audio_code(void *i2c_dev_handle, unsigned char vol) {
    s_audio_dev_handle = (i2c_master_dev_handle_t)i2c_dev_handle; // 接收句柄
    char error = 0;
    for (int i = 0; i < 3; i++) {
        char ret = ACM86xx_init(vol);
        if (ret != 0) {
            vTaskDelay(50 / portTICK_PERIOD_MS);
            error++;
            if (error > 5) {
                return -1;
            }
        } else {
            break;
        }
    }
    return 0;
}
void set_volume_audio_code(int val) {
    volumeControl(val);
}

