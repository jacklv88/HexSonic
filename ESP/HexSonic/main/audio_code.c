void set_mute_audio_code(char status) {
    audio_write_reg(0x00, 0x00);
    if (status) {
        audio_write_reg(0x04, 0x0e); // Mute
        ESP_LOGI(TAG, "Audio Muted");
    } else {
        audio_write_reg(0x04, 0x03); // Unmute
        ESP_LOGI(TAG, "Audio Unmuted");
    }
}

void set_volume_audio_code(int vol, char delay) {
    if (vol > 100) vol = 100;
    
    unsigned int tmp = 0;
    int index = vol / 2;
    
    // 计算音量值
    if (vol % 2 == 0) {
        if (index > 0) index -= 1;
        tmp = my_acm8615VolTable[49 - index];
    } else {
        int index1 = (index + 1 >= 49) ? 49 : index + 1;
        tmp = (my_acm8615VolTable[49 - index] + my_acm8615VolTable[49 - index1]) / 2;
    }

    uint8_t v[4];
    v[0] = (tmp >> 24) & 0xff;
    v[1] = (tmp >> 16) & 0xff;
    v[2] = (tmp >> 8) & 0xff;
    v[3] = (tmp) & 0xff;

    // 写入 Page 5 的音量寄存器 (0xc0-0xc7)
    audio_write_reg(0x00, 0x05);
    audio_write_reg(0xc0, v[0]); audio_write_reg(0xc1, v[1]);
    audio_write_reg(0xc2, v[2]); audio_write_reg(0xc3, v[3]);
    audio_write_reg(0xc4, v[0]); audio_write_reg(0xc5, v[1]);
    audio_write_reg(0xc6, v[2]); audio_write_reg(0xc7, v[3]);

    if (delay) vTaskDelay(pdMS_TO_TICKS(10));
}

// ==========================================
// 4. 初始化入口
// ==========================================
char init_audio_code(void *i2c_dev_handle, unsigned char vol) {
    s_audio_dev_handle = (i2c_master_dev_handle_t)i2c_dev_handle;

    ESP_LOGI(TAG, "Starting ACM86xx Init...");

    // 1. 发送初始化脚本
    for (int i = 0; i < sizeof(m_reg_tab_initialization)/sizeof(struct REG_TAB); i++) {
        audio_write_reg(m_reg_tab_initialization[i].Address, m_reg_tab_initialization[i].Data);
    }
    
    vTaskDelay(pdMS_TO_TICKS(30)); // DSP 等待时间

    // 2. 发送主配置脚本
    for (int i = 0; i < sizeof(m_reg_tab)/sizeof(struct REG_TAB); i++) {
        audio_write_reg(m_reg_tab[i].Address, m_reg_tab[i].Data);
    }

    // 3. 设置初始音量并开音
    set_volume_audio_code(vol, 1);
    set_mute_audio_code(0);

    audio_write_reg( 0x00, 0x00);
    audio_write_reg( 0x04, 0x03);    

    ESP_LOGI(TAG, "ACM86xx Init Finished.");
    return 0;
}