// 全局 I2C 设备句柄
static i2c_master_dev_handle_t s_audio_dev_handle = NULL;

#define Audio_I2C_TIMEOUT_MS 100
#define Audio_ADDR           (0x18 >> 1) // 芯片 I2C 地址

// ==========================================
// 1. 底层 I2C 读写封装 (新版 API)
// ==========================================
static esp_err_t audio_write_reg(uint8_t reg_addr, uint8_t data) {
    if (s_audio_dev_handle == NULL) return ESP_ERR_INVALID_STATE;
    uint8_t buf[2] = {reg_addr, data};
    return i2c_master_transmit(s_audio_dev_handle, buf, 2, Audio_I2C_TIMEOUT_MS);
}

