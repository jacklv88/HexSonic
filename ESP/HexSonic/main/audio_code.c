// 使用新版 API 发送数据
static esp_err_t audio_write_reg(uint8_t reg_addr, uint8_t data) {
    uint8_t buf[2] = {reg_addr, data};
    // i2c_master_transmit 是新一代发送函数
    esp_err_t ret = i2c_master_transmit(s_audio_dev_handle, buf, 2, Audio_I2C_TIMEOUT);
    if (ret != ESP_OK) {
        ESP_LOGI(TAG, "audio reg_addr:%02x data:%02x result:%d", reg_addr, data, ret);
    }
    return ret;
}

// 使用新版 API 读取数据
static esp_err_t audio_read_reg(uint8_t reg_addr, unsigned char *data) {
    // i2c_master_transmit_receive 是新一代读写函数
    esp_err_t ret = i2c_master_transmit_receive(s_audio_dev_handle, &reg_addr, 1, data, 1, Audio_I2C_TIMEOUT);
    if (ret != ESP_OK) {
        ESP_LOGI(TAG, "audio read reg_addr:%02x error result:%d", reg_addr, ret);
    }
    return ret;
}

